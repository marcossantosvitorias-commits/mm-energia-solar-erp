    (new.id, 'Segurança', 'Conferir EPIs e condições do telhado', 40),
    (new.id, 'Instalação', 'Registrar fotos antes da instalação', 50),
    (new.id, 'Instalação', 'Instalar e fixar os módulos', 60),
    (new.id, 'Elétrica', 'Executar conexões CC e CA', 70),
    (new.id, 'Elétrica', 'Realizar aterramento e testes elétricos', 80),
    (new.id, 'Finalização', 'Configurar monitoramento do inversor', 90),
