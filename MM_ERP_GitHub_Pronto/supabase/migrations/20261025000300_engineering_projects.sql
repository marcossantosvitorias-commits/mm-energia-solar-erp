create table if not exists public.engineering_projects (
  id uuid primary key default gen_random_uuid(),
  project_number bigint generated by default as identity unique,
  client_id uuid references public.clients(id) on delete set null,
  title text not null,
  project_type text not null default 'Fotovoltaico',
  status text not null default 'Cadastro' check (status in ('Cadastro','Em análise','Aguardando documentos','Em projeto','Protocolado','Em exigência','Aprovado','Homologado','Cancelado')),
  utility_company text,
  consumer_unit text,
  connection_type text,
  installation_address text,
  city text,
  state text default 'SP',
  system_power_kw numeric(10,3) default 0,
  panel_count integer default 0,
  panel_power_w integer default 0,
  inverter_model text,
  phase text,
  expected_deadline date,
  protocol_number text,
  responsible_name text,
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.engineering_project_activities (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.engineering_projects(id) on delete cascade,
  activity_type text not null default 'Nota',
  title text not null,
  description text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.engineering_project_documents (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.engineering_projects(id) on delete cascade,
  document_type text not null default 'Outro',
  name text not null,
  storage_path text,
  status text not null default 'Pendente' check (status in ('Pendente','Recebido','Validado','Rejeitado')),
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.engineering_project_tasks (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.engineering_projects(id) on delete cascade,
  title text not null,
  status text not null default 'Pendente' check (status in ('Pendente','Em andamento','Concluída')),
  priority text not null default 'Normal' check (priority in ('Baixa','Normal','Alta','Urgente')),
  due_date date,
  assigned_to text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists engineering_projects_status_idx on public.engineering_projects(status);
create index if not exists engineering_projects_client_idx on public.engineering_projects(client_id);
create index if not exists engineering_projects_deadline_idx on public.engineering_projects(expected_deadline);
create index if not exists engineering_project_activities_project_idx on public.engineering_project_activities(project_id, created_at desc);
create index if not exists engineering_project_documents_project_idx on public.engineering_project_documents(project_id, created_at desc);
create index if not exists engineering_project_tasks_project_idx on public.engineering_project_tasks(project_id, due_date);

alter table public.engineering_projects enable row level security;
alter table public.engineering_project_activities enable row level security;
alter table public.engineering_project_documents enable row level security;
alter table public.engineering_project_tasks enable row level security;

drop policy if exists "engineering_projects_authenticated_all" on public.engineering_projects;
create policy "engineering_projects_authenticated_all" on public.engineering_projects for all to authenticated using (public.is_active_user()) with check (public.is_active_user());
drop policy if exists "engineering_project_activities_authenticated_all" on public.engineering_project_activities;
create policy "engineering_project_activities_authenticated_all" on public.engineering_project_activities for all to authenticated using (public.is_active_user()) with check (public.is_active_user());
drop policy if exists "engineering_project_documents_authenticated_all" on public.engineering_project_documents;
create policy "engineering_project_documents_authenticated_all" on public.engineering_project_documents for all to authenticated using (public.is_active_user()) with check (public.is_active_user());
drop policy if exists "engineering_project_tasks_authenticated_all" on public.engineering_project_tasks;
create policy "engineering_project_tasks_authenticated_all" on public.engineering_project_tasks for all to authenticated using (public.is_active_user()) with check (public.is_active_user());

create or replace function public.set_engineering_project_updated_at()
returns trigger language plpgsql set search_path = public as $$
begin new.updated_at = now(); return new; end; $$;

drop trigger if exists engineering_projects_updated_at on public.engineering_projects;
create trigger engineering_projects_updated_at before update on public.engineering_projects for each row execute procedure public.set_engineering_project_updated_at();
drop trigger if exists engineering_project_tasks_updated_at on public.engineering_project_tasks;
create trigger engineering_project_tasks_updated_at before update on public.engineering_project_tasks for each row execute procedure public.set_engineering_project_updated_at();
